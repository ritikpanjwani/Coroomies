import hashlib
import hmac
from pwdlib import PasswordHash
from app.config import OTP_PEPPER_KEY

password_hash = PasswordHash.recommended()


def hash_password(password: str) -> str:
    return password_hash.hash(password)


def verify_password(password: str, password_hash_value: str) -> bool:
    return password_hash.verify(password, password_hash_value)


def hash_otp(otp: str) -> str:
    """Compute HMAC-SHA256 hex digest of an OTP using the server-side pepper key."""
    key = OTP_PEPPER_KEY.encode("utf-8")
    return hmac.new(key, otp.strip().encode("utf-8"), hashlib.sha256).hexdigest()


def verify_otp_hash(submitted_otp: str, stored_token: str) -> bool:
    """Verify submitted OTP against stored token representation.
    Supports:
      1. Primary: HMAC-SHA256 with OTP_PEPPER_KEY (64 hex characters)
      2. Migration fallback: plain SHA-256 (64 hex characters)
         Retirement Plan: OTP TTL is at most 15 minutes (10m for reset, 15m for email change).
         This fallback is only required during a 15-minute rolling deployment window where
         tokens may have been generated by a previous container. After 15 minutes, all valid
         tokens are guaranteed to be HMAC-SHA256 and this fallback can be safely removed.
    
    Obsolete plaintext verification has been removed as all legacy plaintext tokens are expired.
    Uses constant-time comparison (hmac.compare_digest) for all branches.
    """
    clean_submitted = submitted_otp.strip()
    clean_stored = stored_token.strip()

    # 1. Primary: HMAC-SHA256
    expected_hmac = hash_otp(clean_submitted)
    if hmac.compare_digest(clean_stored, expected_hmac):
        return True

    # 2. Migration fallback: Plain SHA-256
    legacy_sha256 = hashlib.sha256(clean_submitted.encode("utf-8")).hexdigest()
    if hmac.compare_digest(clean_stored, legacy_sha256):
        return True

    return False
